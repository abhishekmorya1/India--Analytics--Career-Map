def title(fig, main, sub):
    h = fig.get_figheight()  # offsets in inches so short and tall figures look the same
    fig.text(0.01, 1 - 0.05 / h, main, fontsize=14, fontweight="bold", va="top", color=INK)
    fig.text(0.01, 1 - 0.42 / h, sub, fontsize=9.5, va="top", color=INK2, linespacing=1.4)


def save(fig, name):
    fig.savefig(FIG / name, bbox_inches="tight", pad_inches=0.25)
    plt.close(fig)
    print("saved", FIG / name)


