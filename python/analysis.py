# %% [markdown]
# ## 3. Skill premium with controls
# Log-salary regression: role + experience (+ experience squared) + skill flags.
# "% difference" = how much higher (or lower) pay is for postings that ask for the skill, other things equal.
# Bootstrap 95% interval (500 resamples). This is ASSOCIATION, not what learning the skill would do for you.

# %%
CORE = ["sql", "python", "power bi", "tableau", "excel", "aws", "azure", "spark", "machine learning", "snowflake"]
d = sal.dropna(subset=["exp_min"]).copy()
for s in CORE:
    d[s] = d.job_id.isin(skills[skills.skill == s].job_id).astype(float)
d["ly"] = np.log(d.salary_lpa)
y = d["ly"].values


def design(df, with_exp):
    M = pd.get_dummies(df.role).drop(columns="BI / MIS / Reporting").astype(float)  # baseline = BI / MIS
    if with_exp:
        M["exp"] = df.exp_min.clip(upper=12)
        M["exp2"] = M["exp"] ** 2
    for s in CORE:
        M[s] = df[s]
    M.insert(0, "const", 1.0)
    return M


def fit(M, yy):
    return np.linalg.lstsq(M.values, yy, rcond=None)[0]


M_full, M_role = design(d, True), design(d, False)
b_full, b_role = fit(M_full, y), fit(M_role, y)
rng = np.random.default_rng(SEED)
boots = np.empty((500, len(b_full)))
for k in range(500):
    i = rng.integers(0, len(d), len(d))
    boots[k] = fit(M_full.iloc[i], y[i])
cols = list(M_full.columns)
pct = lambda b: (np.exp(b) - 1) * 100
prem = pd.DataFrame({
    "skill": CORE,
    "role_only": [pct(b_role[list(M_role.columns).index(s)]) for s in CORE],
    "role_plus_exp": [pct(b_full[cols.index(s)]) for s in CORE],
    "lo": [pct(np.percentile(boots[:, cols.index(s)], 2.5)) for s in CORE],
    "hi": [pct(np.percentile(boots[:, cols.index(s)], 97.5)) for s in CORE],
    "n_with": [int(d[s].sum()) for s in CORE],
})
prem["clear"] = (prem.lo > 0) | (prem.hi < 0)
prem = prem.sort_values("role_plus_exp")
print(prem.round(1).to_string(index=False))

fig, ax = plt.subplots(figsize=(8.8, 5.6))
ypos = np.arange(len(prem))
ax.axvline(0, color=AXIS, lw=1.2, zorder=1)
for yi, (_, r) in zip(ypos, prem.iterrows()):
    ax.plot([r.lo, r.hi], [yi, yi], color=BLUE, lw=2, alpha=0.9 if r.clear else 0.35, zorder=2,
            solid_capstyle="round")
ax.scatter(prem.role_only, ypos, s=56, color=ORANGE, edgecolor=SURFACE, linewidth=2, zorder=3,
           label="Role held fixed only")
ax.scatter(prem.role_plus_exp, ypos, s=72, color=BLUE, edgecolor=SURFACE, linewidth=2, zorder=4,
           label="Role + experience held fixed (line = 95% interval)")
for yi, (_, r) in zip(ypos, prem.iterrows()):
    ax.text(1.01, yi, f"{r.role_plus_exp:+.0f}%" + ("" if r.clear else "  (unclear)"),
            transform=ax.get_yaxis_transform(), va="center", fontsize=9, color=INK2)
ax.set_yticks(ypos)
ax.set_yticklabels(prem.skill)
ax.grid(axis="y", visible=False)
ax.set_xlabel("Pay difference for postings that list the skill (%)")
ax.set_xlim(min(prem.lo.min(), prem.role_only.min()) - 6, prem.hi.max() + 8)
ax.legend(loc="upper left", fontsize=8.5)
title(fig, "Only Power BI and AWS keep a clear pay edge once role and experience are fixed",
      f"Estimated pay difference per skill, {len(d)} salary postings. Faded line = interval includes zero. "
      "Excel postings pay less.")
fig.subplots_adjust(top=0.85)
save(fig, "04_skill_premium.png")

pt = prem.copy()
for c in ["role_only", "role_plus_exp", "lo", "hi"]:
    pt[c] = pt[c].map(lambda v: f"{v:+.0f}%")
pt["clear"] = np.where(prem.clear, "yes", "no")
findings += [f"## 3. Skill premium ({len(d)} salary postings)\n",
             "Log-salary regression with role, experience and experience squared held fixed. "
             "`role_only` = same model without experience. `lo`/`hi` = 95% bootstrap interval of `role_plus_exp`. "
             "`clear` = interval excludes 0.\n",
             md_table(pt[["skill", "n_with", "role_only", "role_plus_exp", "lo", "hi", "clear"]])]
r2 = 1 - ((y - M_full.values @ b_full) ** 2).sum() / ((y - y.mean()) ** 2).sum()
findings.append(f"Model R-squared (in-sample): {r2:.2f}.\n")

# %% [markdown]
# ## 4. How much of salary can we explain?
# 5-fold cross-validation (R-squared on log salary). Then: which GROUP of features matters most?
# (permute a whole group on held-out data and measure the drop in R-squared)

# %%
TOP_CITIES = ["Bengaluru", "Hyderabad", "Pune", "Delhi NCR", "Chennai", "Mumbai MMR", "Remote"]
X_role = pd.get_dummies(d.role).astype(float)
X_exp = d[["exp_min"]].clip(upper=12).astype(float)
X_skill = d[CORE].astype(float)
X_city = pd.get_dummies(d.metro_group.where(d.metro_group.isin(TOP_CITIES), "Other"), prefix="city").astype(float)
yy = d["ly"].reset_index(drop=True)
sets = {
    "Role only": [X_role],
    "Role + experience": [X_role, X_exp],
    "+ skills": [X_role, X_exp, X_skill],
    "+ skills + city": [X_role, X_exp, X_skill, X_city],
}
kf = KFold(5, shuffle=True, random_state=SEED)
rows = []
for name, parts in sets.items():
    X = pd.concat(parts, axis=1).reset_index(drop=True)
    for mname, mk in [("Ridge", lambda: Ridge(1.0)),
                      ("Random forest", lambda: RandomForestRegressor(300, min_samples_leaf=5, random_state=SEED, n_jobs=-1))]:
        sc = []
        for tr, te in kf.split(X):
            m = mk().fit(X.iloc[tr], yy.iloc[tr])
            sc.append(r2_score(yy.iloc[te], m.predict(X.iloc[te])))
        rows.append((name, mname, np.mean(sc), np.std(sc)))
cvt = pd.DataFrame(rows, columns=["features", "model", "cv_r2", "sd"])
print(cvt.round(3).to_string(index=False))

# grouped permutation importance (random forest, full feature set)
Xf = pd.concat([X_role, X_exp, X_skill, X_city], axis=1).reset_index(drop=True)
groups = {"Role": list(X_role.columns), "Experience": list(X_exp.columns),
          "Skills (10 core)": list(X_skill.columns), "City": list(X_city.columns)}
imp = {k: [] for k in groups}
rg = np.random.default_rng(SEED)
for tr, te in kf.split(Xf):
    m = RandomForestRegressor(300, min_samples_leaf=5, random_state=SEED, n_jobs=-1).fit(Xf.iloc[tr], yy.iloc[tr])
    Xte, yte = Xf.iloc[te], yy.iloc[te]
    base = r2_score(yte, m.predict(Xte))
    for gname, gcols in groups.items():
        drops = []
        for _ in range(10):
            Xp = Xte.copy()
            Xp[gcols] = Xp[gcols].values[rg.permutation(len(Xp))]
            drops.append(base - r2_score(yte, m.predict(Xp)))
        imp[gname].append(np.mean(drops))
gi = pd.DataFrame({"group": list(imp), "r2_drop": [np.mean(v) for v in imp.values()],
                   "sd": [np.std(v) for v in imp.values()]}).sort_values("r2_drop")

fig, ax = plt.subplots(figsize=(8, 3.6))
ax.barh(gi.group, gi.r2_drop, color=BLUE, height=0.55)
ax.errorbar(gi.r2_drop, range(len(gi)), xerr=gi.sd, fmt="none", ecolor=INK2, elinewidth=1.2, capsize=3)
ax.grid(axis="y", visible=False)
for i, (v, sd_) in enumerate(zip(gi.r2_drop, gi.sd)):
    ax.text(max(v, 0) + sd_ + 0.015, i, f"{v:.2f}", va="center", fontsize=9.5, color=INK2)
ax.set_xlabel("Drop in R-squared when the group is shuffled (higher = matters more)")
ax.set_xlim(0, gi.r2_drop.max() * 1.3)
title(fig, "Experience matters most; skills and city add little on top",
      "Random forest, 5-fold cross-validation, grouped permutation importance. "
      "Role and skills overlap, so they share credit.")
fig.subplots_adjust(top=0.78)
save(fig, "05_what_drives_salary.png")

findings += ["## 4. Salary model (5-fold cross-validated R-squared on log salary)\n",
             md_table(cvt.assign(cv_r2=cvt.cv_r2.round(2), sd=cvt.sd.round(2))),
             "Importance by feature group (drop in R-squared when shuffled):\n",
             md_table(gi.sort_values("r2_drop", ascending=False).round(3))]

