# %% [markdown]
# ## 2. Skill stacks - which skills travel together?
# Lift = how much more (or less) often two skills appear in the same posting than if they were independent.
# Computed over ALL analytics postings (not only salary ones).

# %%
ORDER = ["excel", "power bi", "tableau", "data visualization", "sql", "python", "machine learning",
         "aws", "azure", "snowflake", "databricks", "etl", "spark", "airflow", "hadoop", "kafka"]
P = (skills[skills.skill.isin(ORDER)].assign(v=1)
     .pivot_table(index="job_id", columns="skill", values="v", fill_value=0)
     .reindex(columns=ORDER, fill_value=0))
N = len(jobs)
C = P.T.dot(P).astype(float)
cnt = np.diag(C).copy()
expected = np.outer(cnt, cnt) / N
lift = C.values / expected
lift[np.eye(len(ORDER), dtype=bool)] = np.nan
lift[expected < 5] = np.nan                      # too rare to judge
ll = np.log2(np.clip(lift, 1 / 8, 8))

cmap = LinearSegmentedColormap.from_list("div", ["#e34948", "#f0efec", "#1c5cab"])
fig, ax = plt.subplots(figsize=(9.2, 7.6))
im = ax.imshow(np.ma.masked_invalid(ll), cmap=cmap, vmin=-3, vmax=3)
ax.set_facecolor("#f4f3ef")
ax.grid(False)
ax.set_xticks(range(len(ORDER)))
ax.set_yticks(range(len(ORDER)))
ax.set_xticklabels(ORDER, rotation=45, ha="right", fontsize=9)
ax.set_yticklabels(ORDER, fontsize=9)
ax.tick_params(length=0)
for s in ax.spines.values():
    s.set_visible(False)
for i in range(len(ORDER)):
    for j in range(len(ORDER)):
        v = lift[i, j]
        if not np.isnan(v) and (v >= 2 or v <= 0.5):
            ax.text(j, i, f"{v:.1f}", ha="center", va="center", fontsize=7.5,
                    color="white" if abs(ll[i, j]) > 1.6 else INK)
cb = fig.colorbar(im, ax=ax, shrink=0.6, pad=0.02)
cb.set_ticks([-3, -2, -1, 0, 1, 2, 3])
cb.set_ticklabels(["1/8x", "1/4x", "1/2x", "chance", "2x", "4x", "8x"])
cb.ax.tick_params(labelsize=8, length=0)
cb.outline.set_visible(False)
cb.set_label("Red: asked together less than chance      Blue: more than chance", fontsize=8.5, color=INK2)
title(fig, "Two skill stacks: dashboards on one side, big-data tooling on the other",
      "How much more often two skills share a posting than if they were independent (all analytics postings)."
      "\nNumbers shown where lift is 2x or more, or 0.5x or less.")
fig.subplots_adjust(top=0.86)
save(fig, "03_skill_stacks_heatmap.png")

